#include "philo.h"
#include <unistd.h>
#include <stdlib.h>
#include <sys/time.h>

void	ft_ms_usleep(int n)
{
	usleep(n * 1000);
}

t_ms	curr_time(void)
{
	struct timeval	tv;

	gettimeofday(&tv, NULL);
	return ((tv.tv_sec * 1000) + (tv.tv_usec / 1000));
}
